//! Places, bodies and regions: many places at once (Part III F11, Wave 11 regions).
//!
//! A **body** is a place with its own ground ([`BodyId`]): the home world with its sky
//! ([`BodyId::Home`]), the existing Moon ([`BodyId::Moon`], which still lives in the home
//! terrain high above its fixed column and plays exactly as before), and the bodies the space
//! generator places ([`BodyId::Space`], keyed by [`SpaceBodyKey`]). A **place** is where a player
//! is ([`Place`]): on a body, or in free flight in [`Place::Space`].
//!
//! Every place lives in a **store** ([`StoreKey`]): the ground, entities and fluids one pass of
//! the tick runs over. The home world and the Moon share the home store (the world's own
//! terrain and entity store); every space body has a store of its own, created the first time
//! someone arrives ([`BodyWorld`], generated by a [`BodyGenerator`]); free flight shares the
//! space store (empty ground). [`crate::WorldState::simulate_tick`] runs one pass per occupied
//! store and freezes the rest (see `world/places.rs`).
//!
//! Inside a store, a **region** ([`RegionId`]) is one [`crate::position::SECTOR_TILES`]-square
//! cell of tiles. The regions round every occupant are awake; entities elsewhere are frozen
//! (kept, not ticked) until someone comes back ([`occupied_cells`]).
//!
//! Generation is a pure function of the world seed and the body key ([`generator_for`]), so a
//! host, its clients and a reloaded save rebuild the same ground.

