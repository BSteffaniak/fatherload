//! Alien towns on round bodies (Wave 12 aliens track): where they stand, what is in them and
//! who lives there.
//!
//! * **Sites** ([`TownSite`], [`sites`]): a settled planet holds two or three towns, a moon one,
//!   spread evenly round its ring (a lap of the body passes every one). Each site is a span of
//!   level ground at the raw surface's height at its centre: the planet generator flattens the
//!   span ([`flattened_row`], easing back to the hills over [`FADE_COLUMNS`]), paves its top
//!   ([`town_tile`]), keeps caves out from under it and buries three lexicon stones beneath it.
//!   A theme that levels its own settlement site (the wild and frontier worlds,
//!   [`crate::planet::PlanetThemeHooks::settlement_site`]) holds one town there instead, on its
//!   own ground: the jungle's clearing, the archipelago's island, the oasis rim (Wave 12
//!   integration). The even spread serves the barren, rocky and icy grounds.
//! * **Layout** ([`AlienTown`]): the species' own buildings ([`AlienBuildingKind`]): the
//!   landmark at the middle (a Vessi song spire, a Tokkari forge chimney, a Siphra memory
//!   pylon), the elder's house and the trade hall beside it, the lexicon house and the
//!   workshop, the dwellings, a monument plinth a quest can raise, and homes for sale at the
//!   ends.
//! * **Residents**: six to eight of the species, generated by the people engine in the
//!   species' culture with its trades (the trader, the lexicon keeper, the elder and the
//!   builder first). The town is a [`Settlement`] (`Settlement::alien_town`), so they keep
//!   schedules, sleep in the dwellings and work by their buildings.
//! * **Ids** ([`town_id`], [`is_alien_town`]): a town's [`VillageId`] is in its own range
//!   (`0x2000_0000..0x3000_0000`), a hash of the body's ground seed and the town's index, and
//!   resolves back to its town through a per-process registry filled whenever a body's towns
//!   are computed ([`towns_of`]); a world registers every stored body's towns on load.

#![allow(
    clippy::cast_possible_truncation,
    clippy::cast_possible_wrap,
    clippy::cast_sign_loss,
    reason = "hashed rolls reduced into small bounded ranges"
)]

