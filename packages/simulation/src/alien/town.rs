/// Columns over which a town's level ground eases back into the hills.
pub const FADE_COLUMNS: i32 = 14;
/// Rows of paving on top of a town's ground.
pub const PAVING_ROWS: i32 = 2;
/// Rows below a town's ground caves keep clear of.
pub const CAVE_FREE_ROWS: i32 = 34;
/// Lexicon stones buried under each town.
pub const LEXICON_STONES: usize = 3;
/// The range alien town ids live in (bit 29 set, bit 28 and the camp and sky flags clear).
pub const ALIEN_TOWN_FLAG: u32 = 0x2000_0000;
const ALIEN_TOWN_MASK: u32 = 0xF000_0000;

/// A splitmix step.
const fn mix(mut z: u64) -> u64 {
    z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Whether `id` names an alien town.
#[must_use]
pub const fn is_alien_town(id: VillageId) -> bool {
    id.0 & ALIEN_TOWN_MASK == ALIEN_TOWN_FLAG
}

/// The id of town `index` of the body whose ground is `params`.
#[must_use]
pub const fn town_id(params: &PlanetParams, index: u8) -> VillageId {
    let hash = mix(params.seed ^ 0x544F_574E_5300_0001) as u32;
    VillageId(ALIEN_TOWN_FLAG | ((hash & 0x03FF_FFFF) << 2) | (index as u32 & 3))
}

/// Where a town stands on its body's strip.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct TownSite {
    pub index: u8,
    pub species: AlienSpecies,
    /// The middle column (`0..W`, never across the strip's seam).
    pub centre: i32,
    /// Columns of level ground each side of the middle.
    pub half_width: i32,
    /// The first ground row of the level span.
    pub ground_row: i32,
    /// The lexicon stones under it: `(column, row)`.
    pub stones: [(i32, i32); LEXICON_STONES],
}

impl TownSite {
    /// The first column of the level span.
    #[must_use]
    pub const fn first_column(&self) -> i32 {
        self.centre - self.half_width
    }

    /// The last column of the level span.
    #[must_use]
    pub const fn last_column(&self) -> i32 {
        self.centre + self.half_width
    }
}

/// How many towns a body with `params` holds.
#[must_use]
pub fn town_count(params: &PlanetParams) -> u8 {
    if params.folk == 0 {
        return 0;
    }
    if params.radius >= crate::space::PLANET_RADIUS.0 {
        2 + u8::from(mix(params.seed ^ 0x544F_574E_5300_0002).is_multiple_of(3))
    } else {
        1
    }
}

/// The town sites of `ground` (empty for a body nobody settled). A pure function of its
/// params; the raw surface (before flattening) sets each town's level.
#[must_use]
pub fn sites(ground: &PlanetGround) -> [Option<TownSite>; 3] {
    let params = *ground.params();
    let mut out = [None; 3];
    let Some(species) = AlienSpecies::from_folk(params.folk) else {
        return out;
    };
    let count = i32::from(town_count(&params));
    let width = ground.strip_width();
    if count == 0 || width <= 0 {
        return out;
    }
    let base_half = span_half(species);
    // A theme that levels its own settlement site (the wild and frontier worlds) holds its
    // first town there, on the theme's own ground (Wave 12 integration: the theme's
    // site-finder). A wild world builds its whole ground itself, so that is its one town (an
    // escort there runs to the far side of the body); a frontier world's others spread round
    // the rest of the lap on ground the generator levels for them, as anywhere.
    if let Some((centre, _)) = ground.hooks().settlement_site(ground) {
        let centre = centre.rem_euclid(width);
        let roll = mix(params.seed ^ 0x544F_574E_5300_0010);
        let ground_row = ground.raw_surface_row(i64::from(centre));
        out[0] = Some(TownSite {
            index: 0,
            species,
            centre,
            half_width: base_half,
            ground_row,
            stones: stones_under(roll, centre, base_half, ground_row),
        });
        if ground.hooks().world().is_some() {
            return out;
        }
        for index in 1..count {
            let roll = mix(params.seed ^ 0x544F_574E_5300_0010 ^ (index as u64) << 32);
            let half = base_half + (roll % 7) as i32;
            let margin = half + FADE_COLUMNS + 4;
            let other = (centre + width * index / count)
                .rem_euclid(width)
                .clamp(margin, (width - margin).max(margin));
            let ground_row = ground.raw_surface_row(i64::from(other));
            out[usize::try_from(index).unwrap_or(0)] = Some(TownSite {
                index: u8::try_from(index).unwrap_or(0),
                species,
                centre: other,
                half_width: half,
                ground_row,
                stones: stones_under(roll, other, half, ground_row),
            });
        }
        return out;
    }
    for index in 0..count {
        let roll = mix(params.seed ^ 0x544F_574E_5300_0010 ^ (index as u64) << 32);
        let half = base_half + (roll % 7) as i32;
        let slot = width / count;
        let jitter_span = (slot / 6).max(1);
        let jitter = ((roll >> 16) % (2 * jitter_span as u64 + 1)) as i32 - jitter_span;
        let margin = half + FADE_COLUMNS + 4;
        let centre = (slot * index + slot / 2 + jitter).clamp(margin, (width - margin).max(margin));
        let ground_row = ground.raw_surface_row(i64::from(centre));
        out[usize::try_from(index).unwrap_or(0)] = Some(TownSite {
            index: u8::try_from(index).unwrap_or(0),
            species,
            centre,
            half_width: half,
            ground_row,
            stones: stones_under(roll, centre, half, ground_row),
        });
    }
    out
}

/// The lexicon stones buried under a town centred on `centre` (`half` columns either side)
/// whose ground is `ground_row`.
fn stones_under(
    roll: u64,
    centre: i32,
    half: i32,
    ground_row: i32,
) -> [(i32, i32); LEXICON_STONES] {
    let mut stones = [(0, 0); LEXICON_STONES];
    for (stone, slot_stone) in (0_i32..).zip(stones.iter_mut()) {
        let stone_roll = mix(roll ^ (stone as u64 + 1));
        let column = centre + (stone - 1) * half * 2 / 3 + (stone_roll % 9) as i32 - 4;
        let row = ground_row + 7 + ((stone_roll >> 8) % 20) as i32;
        *slot_stone = (column, row);
    }
    stones
}

/// Distance (columns) from `column` to `centre` round a strip `width` wide.
#[must_use]
pub const fn wrapped_distance(column: i64, centre: i32, width: i32) -> i64 {
    if width <= 0 {
        return (column - centre as i64).abs();
    }
    let width = width as i64;
    let mut delta = (column - centre as i64).rem_euclid(width);
    if delta > width / 2 {
        delta = width - delta;
    }
    delta
}

/// The surface row at `column` with the towns' level ground over the raw row `raw`.
#[must_use]
pub fn flattened_row(sites: &[Option<TownSite>; 3], width: i32, column: i64, raw: i32) -> i32 {
    for site in sites.iter().flatten() {
        let distance = wrapped_distance(column, site.centre, width);
        let half = i64::from(site.half_width);
        if distance <= half {
            return site.ground_row;
        }
        let fade = i64::from(FADE_COLUMNS);
        if distance <= half + fade {
            let t = distance - half;
            let level = i64::from(site.ground_row);
            let blended = level + (i64::from(raw) - level) * t / fade;
            return i32::try_from(blended).unwrap_or(raw);
        }
    }
    raw
}

/// Whether caves keep clear of `(column, row)` (under a town's span and its fades).
#[must_use]
pub fn keeps_caves_out(sites: &[Option<TownSite>; 3], width: i32, column: i64, row: i32) -> bool {
    sites.iter().flatten().any(|site| {
        wrapped_distance(column, site.centre, width) <= i64::from(site.half_width + FADE_COLUMNS)
            && row < site.ground_row + CAVE_FREE_ROWS
    })
}

/// The town tile at `(column, row)` (`surface`: the flattened surface row there), if a town
/// puts one there: its paving on the level span's top rows, a lexicon stone under it.
#[must_use]
pub fn town_tile(
    sites: &[Option<TownSite>; 3],
    width: i32,
    column: i64,
    row: i32,
    surface: i32,
) -> Option<TileKind> {
    for site in sites.iter().flatten() {
        let distance = wrapped_distance(column, site.centre, width);
        if distance > i64::from(site.half_width) {
            continue;
        }
        if row >= surface && row < surface + PAVING_ROWS {
            return Some(TileKind::Alien(AlienTile::paving(site.species)));
        }
        let wrapped = if width > 0 {
            column.rem_euclid(i64::from(width))
        } else {
            column
        };
        if site.stones.iter().any(|(stone_column, stone_row)| {
            i64::from(*stone_column) == wrapped && *stone_row == row
        }) {
            return Some(TileKind::Alien(AlienTile::LexiconStone(site.species)));
        }
    }
    None
}

/// What a town building is (its art and its use).
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub enum AlienBuildingKind {
    /// Where a family lives.
    Dwelling,
    /// The trader's hall: ores bought, goods sold.
    TradeHall,
    /// The elder's house: quests and the story.
    ElderHouse,
    /// The lexicon house: lessons in the tongue.
    LexiconHouse,
    /// The builder's workshop: homes built to order.
    Workshop,
    /// The town's landmark (a song spire, a forge chimney, a memory pylon).
    Landmark,
    /// A plinth a quest's raising crowns with a monument.
    Monument,
    /// A plot for sale: a home is built here for a player.
    HomePlot,
}

impl AlienBuildingKind {
    /// What the species call it.
    #[must_use]
    pub const fn name(self, species: AlienSpecies) -> &'static str {
        match (self, species) {
            (Self::Dwelling, AlienSpecies::Vessi) => "snow-vault",
            (Self::Dwelling, AlienSpecies::Tokkari) => "mound-home",
            (Self::Dwelling, AlienSpecies::Siphra) => "lantern-pod",
            (Self::TradeHall, _) => "trade hall",
            (Self::ElderHouse, _) => "elder's house",
            (Self::LexiconHouse, _) => "lexicon house",
            (Self::Workshop, _) => "builder's workshop",
            (Self::Landmark, AlienSpecies::Vessi) => "song spire",
            (Self::Landmark, AlienSpecies::Tokkari) => "forge chimney",
            (Self::Landmark, AlienSpecies::Siphra) => "memory pylon",
            (Self::Monument, _) => "monument plinth",
            (Self::HomePlot, _) => "plot for sale",
        }
    }

    /// The village building kind routines read it as (`None`: not a lot people use).
    #[must_use]
    pub const fn lot_kind(self) -> Option<BuildingKind> {
        match self {
            Self::Dwelling => Some(BuildingKind::House),
            Self::TradeHall => Some(BuildingKind::Market),
            Self::ElderHouse => Some(BuildingKind::Hall),
            Self::LexiconHouse => Some(BuildingKind::MapRoom),
            Self::Workshop => Some(BuildingKind::Workshop),
            Self::Landmark => Some(BuildingKind::Shrine),
            Self::Monument | Self::HomePlot => None,
        }
    }
}

/// One building of a town.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct AlienBuilding {
    pub kind: AlienBuildingKind,
    /// Its index in the town's building list (home plots are named by it).
    pub index: u8,
    pub first_column: i32,
    pub width: i32,
    /// Its height in tiles (art).
    pub height: i32,
}

impl AlienBuilding {
    /// The column of its door (its middle).
    #[must_use]
    pub const fn door_column(&self) -> i32 {
        self.first_column + self.width / 2
    }

    /// The last column it covers.
    #[must_use]
    pub const fn last_column(&self) -> i32 {
        self.first_column + self.width - 1
    }
}

/// A town: its site, name, buildings and residents.
#[derive(Clone, Debug)]
pub struct AlienTown {
    pub id: VillageId,
    pub params: PlanetParams,
    pub site: TownSite,
    pub species: AlienSpecies,
    pub name: String,
    pub buildings: Vec<AlienBuilding>,
    pub population: Population,
}

impl AlienTown {
    /// The first column of its level ground.
    #[must_use]
    pub const fn first_column(&self) -> i32 {
        self.site.first_column()
    }

    /// The last column of its level ground.
    #[must_use]
    pub const fn last_column(&self) -> i32 {
        self.site.last_column()
    }

    /// Its ground row.
    #[must_use]
    pub const fn ground_row(&self) -> i32 {
        self.site.ground_row
    }

    /// The building of `kind` (the first one).
    #[must_use]
    pub fn building(&self, kind: AlienBuildingKind) -> Option<&AlienBuilding> {
        self.buildings.iter().find(|building| building.kind == kind)
    }

    /// The home plots for sale, by building index.
    pub fn home_plots(&self) -> impl Iterator<Item = &AlienBuilding> + '_ {
        self.buildings
            .iter()
            .filter(|building| building.kind == AlienBuildingKind::HomePlot)
    }

    /// The resident who keeps role slot `slot` of the species' trades (0 trader, 1 lexicon
    /// keeper, 2 elder, 3 builder).
    #[must_use]
    pub fn keeper(&self, slot: usize) -> Option<&Character> {
        self.population.characters.get(slot)
    }

    /// Whether strip column `column` is in the town (its level span, wrapped round a strip
    /// `width` wide).
    #[must_use]
    pub const fn contains_column(&self, column: i64, width: i32) -> bool {
        wrapped_distance(column, self.site.centre, width) <= self.site.half_width as i64
    }

    /// The strip width of its body.
    #[must_use]
    pub fn strip_width(&self) -> i32 {
        PlanetGround::new(self.params).strip_width()
    }
}

/// The resident slot of the trader, the lexicon keeper, the elder and the builder.
pub const TRADER: usize = 0;
pub const TEACHER: usize = 1;
pub const ELDER: usize = 2;
pub const BUILDER: usize = 3;

/// Widths of a town's buildings for `species`: (dwelling, hall, landmark, plot).
const fn widths(species: AlienSpecies) -> (i32, i32, i32, i32) {
    match species {
        AlienSpecies::Vessi => (9, 11, 5, 11),
        AlienSpecies::Tokkari => (8, 12, 4, 10),
        AlienSpecies::Siphra => (7, 9, 3, 9),
    }
}

/// Gap (columns) between a town's buildings.
const GAP: i32 = 2;

/// Columns each side of a town's middle its whole layout needs (the wider side, with the
/// landmark's half and a step of street at the end).
#[must_use]
pub const fn span_half(species: AlienSpecies) -> i32 {
    let (dwelling, hall, landmark, plot) = widths(species);
    let left = hall + (dwelling + 1) + (landmark + 2) + 2 * dwelling + plot + 5 * GAP;
    let right = hall + dwelling + 2 * dwelling + plot + 4 * GAP;
    let side = if left > right { left } else { right };
    landmark / 2 + side + GAP + 2
}

/// Heights (tiles) of a town's buildings for `species`: (dwelling, hall, landmark).
const fn heights(species: AlienSpecies) -> (i32, i32, i32) {
    match species {
        AlienSpecies::Vessi => (3, 4, 11),
        AlienSpecies::Tokkari => (3, 4, 8),
        AlienSpecies::Siphra => (5, 6, 10),
    }
}

fn layout(params: &PlanetParams, site: TownSite) -> AlienTown {
    let species = site.species;
    let def = species.def();
    let id = town_id(params, site.index);
    let roll = mix(params.seed ^ u64::from(id.0));
    let name = format!(
        "{}{}",
        def.town_first[(roll % def.town_first.len() as u64) as usize],
        def.town_second[((roll >> 12) % def.town_second.len() as u64) as usize]
    );
    let residents = 6 + usize::try_from((roll >> 24) % 3).unwrap_or(0);
    let population = population(params.seed, id, species, residents, &name);
    let (dwelling_w, hall_w, landmark_w, plot_w) = widths(species);
    let (dwelling_h, hall_h, landmark_h) = heights(species);
    // From the middle outward: the landmark, then each side in turn.
    let mut right: Vec<(AlienBuildingKind, i32, i32)> = vec![
        (AlienBuildingKind::TradeHall, hall_w, hall_h),
        (AlienBuildingKind::Workshop, dwelling_w, dwelling_h),
    ];
    let mut left: Vec<(AlienBuildingKind, i32, i32)> = vec![
        (AlienBuildingKind::ElderHouse, hall_w, hall_h + 1),
        (
            AlienBuildingKind::LexiconHouse,
            dwelling_w + 1,
            dwelling_h + 1,
        ),
    ];
    left.push((AlienBuildingKind::Monument, landmark_w + 2, 3));
    let dwellings = residents.div_ceil(2).min(4);
    for index in 0..dwellings {
        let entry = (AlienBuildingKind::Dwelling, dwelling_w, dwelling_h);
        if index % 2 == 0 {
            right.push(entry);
        } else {
            left.push(entry);
        }
    }
    right.push((AlienBuildingKind::HomePlot, plot_w, 0));
    left.push((AlienBuildingKind::HomePlot, plot_w, 0));
    let gap = GAP;
    let mut buildings = Vec::new();
    let landmark_first = site.centre - landmark_w / 2;
    buildings.push(AlienBuilding {
        kind: AlienBuildingKind::Landmark,
        index: 0,
        first_column: landmark_first,
        width: landmark_w,
        height: landmark_h,
    });
    let mut cursor = landmark_first + landmark_w + gap;
    for (kind, width, height) in right {
        if cursor + width - 1 > site.last_column() {
            break;
        }
        buildings.push(AlienBuilding {
            kind,
            index: 0,
            first_column: cursor,
            width,
            height,
        });
        cursor += width + gap;
    }
    let mut cursor = landmark_first - gap;
    for (kind, width, height) in left {
        if cursor - width + 1 < site.first_column() {
            break;
        }
        buildings.push(AlienBuilding {
            kind,
            index: 0,
            first_column: cursor - width + 1,
            width,
            height,
        });
        cursor -= width + gap;
    }
    buildings.sort_by_key(|building| building.first_column);
    for (index, building) in buildings.iter_mut().enumerate() {
        building.index = u8::try_from(index).unwrap_or(u8::MAX);
    }
    AlienTown {
        id,
        params: *params,
        site,
        species,
        name,
        buildings,
        population,
    }
}

/// The residents of town `id`: `count` of `species`, in its trades.
fn population(
    seed: u64,
    id: VillageId,
    species: AlienSpecies,
    count: usize,
    name: &str,
) -> Population {
    let def = species.def();
    let mut population = generate_population(seed, id, species.culture(), count);
    for (index, character) in population.characters.iter_mut().enumerate() {
        let role = def.trades[index % def.trades.len()];
        if character.role != role {
            character.role = role;
            let (youngest, oldest) = role.ages();
            character.age = character.age.clamp(youngest, oldest);
            character.offer = role.offer();
            character.history = crate::people::character::history(seed, character);
        }
        if index == ELDER {
            // The eldest voice is old even for them.
            character.age = character.age.max(70);
        }
    }
    name.clone_into(&mut population.village_name);
    population
}

/// Every town of the body whose ground is `params`, in index order (memoized per process;
/// their ids are registered for [`town_by_id`]).
#[must_use]
pub fn towns_of(params: &PlanetParams) -> Arc<Vec<Arc<AlienTown>>> {
    static CACHE: Mutex<BTreeMap<PlanetParams, Arc<Vec<Arc<AlienTown>>>>> =
        Mutex::new(BTreeMap::new());
    if let Some(found) = CACHE
        .lock()
        .unwrap_or_else(PoisonError::into_inner)
        .get(params)
    {
        return Arc::clone(found);
    }
    let towns: Vec<Arc<AlienTown>> = if params.folk == 0 {
        Vec::new()
    } else {
        let ground = PlanetGround::new(*params);
        ground
            .town_sites()
            .iter()
            .flatten()
            .map(|site| Arc::new(layout(params, *site)))
            .collect()
    };
    {
        let mut registry = REGISTRY.lock().unwrap_or_else(PoisonError::into_inner);
        for town in &towns {
            registry.insert(town.id.0, (*params, town.site.index));
        }
    }
    let towns = Arc::new(towns);
    let mut cache = CACHE.lock().unwrap_or_else(PoisonError::into_inner);
    if cache.len() >= 256 {
        cache.clear();
    }
    cache.insert(*params, Arc::clone(&towns));
    towns
}

/// Alien town ids this process has seen, with their body's params and index.
static REGISTRY: Mutex<BTreeMap<u32, (PlanetParams, u8)>> = Mutex::new(BTreeMap::new());

/// The town `id` names, if this process has seen its body (every stored body's towns are
/// registered when a world is built or loaded, and whenever a body's towns are computed).
#[must_use]
pub fn town_by_id(id: VillageId) -> Option<Arc<AlienTown>> {
    if !is_alien_town(id) {
        return None;
    }
    let (params, index) = *REGISTRY
        .lock()
        .unwrap_or_else(PoisonError::into_inner)
        .get(&id.0)?;
    towns_of(&params)
        .iter()
        .find(|town| town.site.index == index)
        .cloned()
}

/// Registers the towns of the body whose ground is `params` (a world does this for every
/// stored body when it is built or loaded).
pub fn register(params: &PlanetParams) {
    let _towns = towns_of(params);
}

/// Town `id`'s routine view (residents sleep in the dwellings and work by their buildings).
#[must_use]
pub fn settlement(id: VillageId) -> Option<Arc<Settlement>> {
    static CACHE: Mutex<BTreeMap<u32, Arc<Settlement>>> = Mutex::new(BTreeMap::new());
    if let Some(found) = CACHE
        .lock()
        .unwrap_or_else(PoisonError::into_inner)
        .get(&id.0)
    {
        return Some(Arc::clone(found));
    }
    let town = town_by_id(id)?;
    let mut lots = Vec::new();
    let mut dwellings = Vec::new();
    for building in &town.buildings {
        let Some(kind) = building.kind.lot_kind() else {
            continue;
        };
        if kind == BuildingKind::House {
            dwellings.push(lots.len());
        }
        lots.push(Lot {
            kind,
            first_column: building.first_column,
            width: building.width,
            enterable: kind == BuildingKind::House,
        });
    }
    let homes: Vec<Option<usize>> = (0..town.population.characters.len())
        .map(|index| (!dwellings.is_empty()).then(|| dwellings[index / 2 % dwellings.len()]))
        .collect();
    let landmark = town
        .building(AlienBuildingKind::Landmark)
        .map_or((town.site.centre - 3, town.site.centre + 3), |building| {
            (building.first_column - 3, building.last_column() + 3)
        });
    let settlement = Arc::new(Settlement::alien_town(
        id,
        town.ground_row(),
        (town.first_column(), town.last_column()),
        landmark,
        lots,
        &homes,
        &town.population,
    ));
    {
        let mut cache = CACHE.lock().unwrap_or_else(PoisonError::into_inner);
        if cache.len() >= 512 {
            cache.clear();
        }
        cache.insert(id.0, Arc::clone(&settlement));
    }
    Some(settlement)
}
